"""SQLite for local use; durable PostgreSQL storage for a single hosted worker.

Only application-authored SQL reaches this module. The PostgreSQL adapter changes
parameter markers, not SQL semantics. Dialect-specific locking and schema creation
are explicit helpers; the reconciliation engine is unchanged.
"""
import os,re,sqlite3,threading
from contextlib import closing
from pathlib import Path
from urllib.parse import urlsplit
import psycopg
from psycopg import sql
from psycopg.pq import TransactionStatus
from psycopg_pool import ConnectionPool

_pools={}
_guard=threading.Lock()
WRITE_LOCK=873210649

def is_postgres(target):return isinstance(target,str) and target.startswith(('postgresql://','postgres://'))
def schema_name():
    value=os.getenv('CROSSCHECK_DB_SCHEMA','crosscheck_state')
    if not re.fullmatch(r'[a-z][a-z0-9_]{0,62}',value):raise ValueError('Invalid application database schema.')
    return value

def _pool(target):
    schema=schema_name();key=(target,schema)
    with _guard:
        if key not in _pools:
            host=urlsplit(target).hostname or ''
            if not (host.endswith('.supabase.com') or host.endswith('.supabase.co')):raise ValueError('Use a Supabase PostgreSQL host for hosted state.')
            cert=str(Path(__file__).parent/'certs/supabase-prod-ca-2021.crt')
            _pools[key]=ConnectionPool(target,min_size=0,max_size=5,timeout=15,max_idle=45,max_lifetime=300,open=True,name='crosscheck-state',kwargs={'sslmode':'verify-full','sslrootcert':cert,'connect_timeout':10,'options':f'-c search_path={schema},pg_catalog -c statement_timeout=20000 -c lock_timeout=10000','application_name':'CrossCheck state'})
        return _pools[key]

class PostgresConnection:
    def __init__(self,pool):self.pool=pool;self.raw=pool.getconn();self.locked=False;self.closed=False
    def __enter__(self):return self
    def __exit__(self,typ,value,tb):
        if typ:self.raw.rollback()
        else:self.raw.commit()
        self.locked=False
    def lock_write(self):
        if not self.locked:
            self.raw.execute('SELECT pg_advisory_xact_lock(%s)',(WRITE_LOCK,));self.locked=True
    def execute(self,query,params=()):
        if re.match(r'\s*(INSERT|UPDATE|DELETE|CREATE|ALTER|DROP|TRUNCATE)\b',query,re.I):self.lock_write()
        # These queries are literals from the app, with no question marks in SQL strings.
        return self.raw.execute(query.replace('?', '%s'),params or None)
    def close(self):
        if self.closed:return
        try:
            if self.raw.info.transaction_status!=TransactionStatus.IDLE:self.raw.rollback()
        finally:self.pool.putconn(self.raw);self.closed=True

def connect(target,timeout=5):
    return PostgresConnection(_pool(target)) if is_postgres(target) else sqlite3.connect(target,timeout=timeout)

def begin_write(db):
    if isinstance(db,PostgresConnection):db.lock_write()
    else:db.execute('BEGIN IMMEDIATE')

def begin_read(db):
    if isinstance(db,PostgresConnection):db.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ')
    else:db.execute('BEGIN')

def table_exists(db,name):
    if isinstance(db,PostgresConnection):return bool(db.execute('SELECT 1 FROM information_schema.tables WHERE table_schema=? AND table_name=?',(schema_name(),name)).fetchone())
    return bool(db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?",(name,)).fetchone())

def initialize(target):
    with closing(connect(target)) as db,db:
        if is_postgres(target):
            db.execute('CREATE TABLE IF NOT EXISTS records (id TEXT PRIMARY KEY,kind TEXT NOT NULL,payload TEXT NOT NULL,owner TEXT,rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE)')
            db.execute('CREATE INDEX IF NOT EXISTS records_owner_kind_order ON records(owner,kind,rowid DESC)')
        else:
            db.execute('CREATE TABLE IF NOT EXISTS records (id TEXT PRIMARY KEY,kind TEXT NOT NULL,payload TEXT NOT NULL,owner TEXT)')
            if 'owner' not in [r[1] for r in db.execute('PRAGMA table_info(records)')]:db.execute('ALTER TABLE records ADD COLUMN owner TEXT')

        db.execute('CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY,email TEXT NOT NULL,name TEXT NOT NULL)')
        db.execute('CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL,expires DOUBLE PRECISION NOT NULL)')
        db.execute('CREATE TABLE IF NOT EXISTS oauth_store (kind TEXT,key TEXT,payload TEXT,PRIMARY KEY(kind,key))')
        db.execute('CREATE TABLE IF NOT EXISTS workspace_archives (id TEXT PRIMARY KEY,owner TEXT NOT NULL,payload TEXT NOT NULL,created_at DOUBLE PRECISION NOT NULL,undone_at DOUBLE PRECISION)')
